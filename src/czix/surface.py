"""Phase-1 helper: static Android/NDK API-surface analysis of an APK.

Reads every lib/<abi>/*.so through the stdlib ELF parser, buckets imported
symbols by subsystem (JNI bridge, EGL/GLES, Vulkan, audio, sensors, media,
assets, bionic…), records DT_NEEDED libraries, and renders reports.

This file is generated tooling for Czix's own runtime work; it intentionally
contains NO Roblox code or assets.
"""
import json
import re
from collections import defaultdict

from . import elfdyn

CATEGORIES = (
    ("java-bridge", r"^(Java_|JNI_OnLoad)"),
    ("egl-window", r"^(egl|eglGetProcAddress|ANativeWindow)"),
    ("gles", r"^(gl[A-Z]|glEnable|glGen|glBind|glUniform|glVertexAttrib|glDraw|glRead|glCompile|glLink|glCreate|glShader|glDelete|glGet)"),
    ("vulkan", r"^vk"),
    ("audio", r"^(AAudio|sl[A-Z]|SLEngine|SL_IID|SLObject|AndroidRecorder|SLEffects)"),
    ("native-activity", r"^ANativeActivity"),
    ("assets-config", r"^(AAsset|AAssetManager|AConfiguration|AChoreographer|ALooper|AInputQueue|AInputEvent|AMotionEvent|AKeyEvent|AObb)"),
    ("sensors", r"^ASensor"),
    ("media-codecs", r"^AMedia"),
    ("camera", r"^ACamera"),
    ("storage", r"^(AStorage|AFile)"),
    ("props", r"^__system_property"),
    ("ndk-core", r"^(Android|A[A-Z][a-z])"),
)

BIONIC_COMMON = re.compile(
    r"^(__|_Z|pthread_|clock_|_ZSt|memcpy|memset|memmove|malloc|calloc|realloc|"
    r"free|mmap|munmap|mprotect|madvise|strlen|strn|strc?py|strcmp|strcat|"
    r"mem[a-z]*|dlopen|dlclose|dlsym|dlerror|dladdr|dl_iterate|write|read$|"
    r"open|close|lseek|fstat|stat|lstat|unlink|rename|mknod|chmod|p?oll|"
    r"epoll|eventfd|timerfd|pipe|prctl|sigaction|sigprocmask|kill|getpid|"
    r"gettid|getuid|geteuid|uname|sysconf|sleep|usleep|nanosleep|abort|"
    r"exit|_exit|atexit|fork|exec|wait4|waitid|getenv|setenv|putenv|"
    r"atoi|strto|atoi64|snprintf|vsprintf|vsscanf|__cxa|__gxx|_Unwind|"
    r"operator[+ ]|^std::|exp[l]?|log[l]?|pow|sqrt|sin|cos|tan|fmod|fabs|"
    r"ceil|floor|round|isnan|rand|srand|qsort|bsearch|time|times|"
    r"gettimeofday|clock_gettime|timer_create|setitimer|alarm)"
)


def summarize(paths) -> dict:
    """Aggregate the native surface across one or more APKs/split-APKs."""
    report = {"abis": {},
              "totals": {"imported": 0, "exported": 0, "library_deps": 0}}
    for apk in paths:
        for info in elfdyn.from_apk(apk):
            parts = info["file"].split("/")
            abi = parts[1] if len(parts) >= 3 else "?"
            slot = report["abis"].setdefault(
                abi, {"libraries": {}, "needed": set(),
                      "cats": defaultdict(set)})
            lib_name = info["file"].rsplit("/", 1)[-1]
            slot["libraries"][lib_name] = {
                "machine": info["machine"], "class": info["class"],
                "imported": len(info["imported"]),
                "exported": len(info["exported"]),
            }
            report["totals"]["imported"] += len(info["imported"])
            report["totals"]["exported"] += len(info["exported"])
            report["totals"]["library_deps"] += len(info["needed"])
            slot["needed"].update(info["needed"])
            for sym in info["imported"]:
                slot["cats"][_categorize(sym)].add(sym)
    for slot in report["abis"].values():
        slot["needed"] = sorted(slot["needed"])
        slot["cats"] = {k: sorted(v) for k, v in slot["cats"].items()}
    return report


def _categorize(sym: str) -> str:
    for label, pat in CATEGORIES:
        if re.match(pat, sym):
            return label
    if BIONIC_COMMON.match(sym):
        return "bionic-cxx-std"
    return "other-platform-relevant"


def render_terminal(rep: dict) -> str:
    lines = []
    for abi, slot in rep["abis"].items():
        lines.append(f"ABI {abi}")
        for lib, meta in sorted(slot["libraries"].items()):
            lines.append(f"  {lib}: ({meta['machine']}/{meta['class']}bit) "
                         f"{meta['imported']} imports, {meta['exported']} exports")
        lines.append(f"  DT_NEEDED ({len(slot['needed'])}): "
                     + ", ".join(slot["needed"]))
        lines.append("  imported-symbol buckets:")
        for cat in sorted(slot["cats"], key=lambda c: -len(slot["cats"][c])):
            lines.append(f"    {cat:22} {len(slot['cats'][cat]):5}")
    t = rep["totals"]
    lines.append(f"totals: imports {t['imported']}, exports {t['exported']}, "
                 f"deps {t['library_deps']}, abis {len(rep['abis'])}")
    return "\n".join(lines)


def render_markdown(rep: dict) -> str:
    out = ["# Roblox Android — native API surface (Phase-1 mapping)",
           "",
           "Auto-generated by `czix surface`. Counts and category lists of ",
           "imported (UND) bionic/NDK symbols and ELF dependencies. No Roblox ",
           "code or assets are reproduced — only public NDK/API symbol names.",
           ""]
    total_cats = defaultdict(int)
    for abi, slot in sorted(rep["abis"].items()):
        out += [f"## ABI `{abi}`", "", "| native library | arch | bits | "
                "imports | exports |", "|---|---|---|---|---|"]
        for lib, meta in sorted(slot["libraries"].items()):
            out.append(f"| `{lib}` | {meta['machine']} | {meta['class']} | "
                       f"{meta['imported']} | {meta['exported']} |")
        out += ["", f"**DT_NEEDED ({len(slot['needed'])}):** "
                + ", ".join(f"`{n}`" for n in slot["needed"]), "",
                "### imports by category", "",
                "| category | n |", "|---|---|"]
        for cat in sorted(slot["cats"], key=lambda c: -len(slot["cats"][c])):
            n = len(slot["cats"][cat])
            total_cats[cat] += n
            out.append(f"| `{cat}` | {n} |")
        out.append("")
        java = slot["cats"].get("java-bridge") or []
        if java:
            out += [f"### JNI bridge (`Java_*`) — {len(java)}", ""]
            out += [f"- `{j}`" for j in sorted(java)]
            out.append("")
        other = slot["cats"].get("other-platform-relevant") or []
        if other:
            out += [f"### other platform-relevant imports (first 80 of "
                    f"{len(other)})", ""]
            out += [f"- `{j}`" for j in sorted(other)[:80]]
            out.append("")
    out += ["## Totals across ABIs", "", "| category | n |", "|---|---|"]
    for cat in sorted(total_cats, key=lambda c: -total_cats[c]):
        out.append(f"| `{cat}` | {total_cats[cat]} |")
    return "\n".join(out) + "\n"


def json_dumps(rep: dict) -> str:
    return json.dumps(rep, indent=2, sort_keys=True)
